import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { readExcelWorkbook } from '../js/core/xlsx-text.js';
import { parseLocalDataFile } from '../js/services/excel-service.js';
import { renderPreviewTable, getEditedData } from '../js/ui/preview-table.js';

const require = createRequire(import.meta.url);
const XLSX = require('../libs/xlsx.full.min.js');
const PizZip = new Function('window', fs.readFileSync('libs/pizzip.min.js', 'utf8') + ';return window.PizZip;')({});
const DOMParser = new Function('window', fs.readFileSync('libs/xmldom.min.js', 'utf8') + ';return window.DOMParser;')({});
Object.assign(globalThis, { PizZip, DOMParser, XLSX });
globalThis.window = { PizZip, DOMParser, XLSX };
const samples = ['Tổ hợp tác cấp nước ấp Vĩnh Phước (tổ 8,9)', 'Nguyễn Thị Hồng Hạnh',
  'Ông Lê Quốc Hùng', 'Đường tỉnh 868', 'Bệnh viện', 'Mỹ Hạnh', 'Nguyễn Văn Bé',
  '  giữ nguyên khoảng trắng  ', 'A & B < C', 'tiếng Việt', '😀'];
const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([['Nội dung', 'Số'], ...samples.map((s, i) => [s, i])]), 'Dữ liệu');
for (const bookSST of [false, true]) {
  const bytes = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx', bookSST });
  const fixed = readExcelWorkbook(bytes, XLSX);
  const sheet = fixed.Sheets[fixed.SheetNames[0]];
  samples.forEach((s, i) => {
    assert.equal(sheet[`A${i + 2}`].v, s);
    assert.equal(sheet[`B${i + 2}`].v, i);
  });
}

// An independent OOXML fixture, not generated by the decoder under test.
const bytes = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx', bookSST: true });
const zip = new PizZip(bytes);
zip.file('xl/sharedStrings.xml', zip.file('xl/sharedStrings.xml').asText()
  .replace(/<si>[\s\S]*?<\/si>/, '<si><r><t>Nội </t></r><r><t>dung</t></r><rPh sb="0" eb="1"><t>ignore</t></rPh></si>'));
const rich = readExcelWorkbook(zip.generate({ type: 'uint8array' }), XLSX);
assert.equal(rich.Sheets[rich.SheetNames[0]].A1.v, 'Nội dung');
const buffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
globalThis.document = { getElementById: () => null };
const imported = await parseLocalDataFile({ name: 'unicode.xlsx', arrayBuffer: async () => buffer });
assert.deepEqual(imported.data.map(row => row['Nội dung']), samples);
let html = '';
const table = { set innerHTML(value) { html = value; } };
globalThis.document = { getElementById: id => id === 'previewDataTable' ? table : null };
renderPreviewTable({ headers: ['Nội dung'], rawData: imported.data });
assert.ok(html.includes('Nguyễn Thị Hồng Hạnh'));
assert.ok(html.includes('A &amp; B &lt; C'));
globalThis.document = { querySelectorAll: () => imported.data.map(row => ({
  querySelector: () => ({ checked: true }),
  querySelectorAll: () => [{ dataset: { col: 'Nội dung' }, value: row['Nội dung'] }]
})) };
assert.deepEqual(getEditedData().map(row => row['Nội dung']), samples);

// Optional original-file audit: assert every string cell without logging private data.
if (process.argv[2]) {
  const original = fs.readFileSync(process.argv[2]);
  const context = { bytes: [...original] };
  vm.createContext(context);
  vm.runInContext(fs.readFileSync('libs/xlsx.full.min.js', 'utf8'), context);
  vm.runInContext('result = XLSX.read(new Uint8Array(bytes).buffer, {type:"array"})', context);
  const fixed = readExcelWorkbook(original, XLSX);
  let count = 0;
  fixed.SheetNames.forEach((name, index) => {
    const expected = context.result.Sheets[context.result.SheetNames[index]];
    for (const [address, cell] of Object.entries(fixed.Sheets[name])) {
      if (cell?.t !== 's') continue;
      assert.equal(cell.v, expected[address].v, `Text mismatch at sheet ${index + 1}, cell ${address}`);
      count++;
    }
  });
  console.log(`Original XLSX: ${count} string cells match independent browser decoding.`);
}
console.log('PASS: Unicode source → XLSX import → preview → edited data; shared/inline/rich text.');
